'use strict';
const assert=require('node:assert/strict');
const S=require('../renoweet-progress-schedule.js'),G=require('../renoweet-progress-gantt.js');
const a=(id,description,progress)=>({id,description,progress});
const p={activities:[a('strip','Strip out the kitchen',100),a('plumb','Relocate pipework',50),a('wall','Finish kitchen walls',25),a('fit','Install kitchen cabinets',0)]};
const s=S.prepare(p,'2026-11-09');s.statusDate='2026-11-13';s.tasks.forEach((t,i)=>{t.days=[2,3,4,3][i]});
s.wbs=[{id:'rough',name:'Preparation',parentId:''},{id:'finish',name:'Fit-out',parentId:''}];
s.tasks.forEach((t,i)=>t.wbsId=i<2?'rough':'finish');
s.milestones=[{id:'signed',code:'M010',name:'Client handover',wbsId:'finish',earliest:'',actualFinish:''}];
const connect=(from,to,type='FS',lag=0)=>({id:from+'_'+to,from,to,type,lag});
s.links=[connect('strip','plumb'),connect('plumb','wall','SS',1),connect('wall','fit'),connect('fit','signed')];
s.baselines.push(S.makeBaseline(p,s,{id:'base',name:'Agreed programme',now:'2026-11-08T12:00:00Z',weights:[20,30,20,30]}));s.baselineId='base';
Object.assign(s.tasks[0],{actualStart:'2026-11-09',actualFinish:'2026-11-10'});
Object.assign(s.tasks[1],{actualStart:'2026-11-12',remaining:3});
const f=S.calculate(p,s,s.statusDate);S.validateReport(f);
const actual=f.rows.find(r=>r.id==='plumb');
assert.equal(actual.remainingStart,'2026-11-16');
const day=date=>Date.parse(date+'T00:00:00Z')/86400000;
const t=G.tracks(actual,day(f.statusDate));
assert.deepEqual(t.actual,[day('2026-11-12'),day('2026-11-14')]);
assert.deepEqual(t.remaining,[day('2026-11-16'),day('2026-11-19')]);
assert.equal(t.unknown,null);
const undated=f.rows.find(r=>r.id==='wall'),u=G.tracks(undated,day(f.statusDate));
assert.equal(u.actual,null);assert(u.unknown);assert(u.remaining);
assert.equal(f.links.length,4);
const chart=G.svg(f);
for(const x of ['Agreed programme','data-gantt-row="strip"','data-gantt-track="baseline"','data-gantt-track="actual"','data-gantt-track="forecast"','data-gantt-track="unknown"','data-gantt-link="FS"','data-gantt-link="SS"','Status date: 2026-11-13','M010','Client handover']){
 if(x==='Agreed programme')assert.equal(f.baseline.name,x);else assert(chart.includes(x),x);
}
assert(!G.svg(f,{links:false}).includes('data-gantt-link'));
const noBaseline=S.calculate(p,{...s,baselineId:''},s.statusDate);
assert(!G.svg(noBaseline).includes('data-gantt-track="baseline"'));assert(G.svg(noBaseline).includes('data-gantt-track="actual"'));
assert.match(G.legend(f,true),/Basisplanning/);
assert.match(G.svg(f,{print:true,isNL:true}),/Peildatum: 2026-11-13/);
const unsafe={...f,rows:f.rows.map((r,i)=>i? r:{...r,description:'<script>bad</script>'})};
assert(!G.svg(unsafe).includes('<script>'));assert(G.svg(unsafe).includes('&lt;script&gt;'));
assert.throws(()=>S.validateReport({...f,links:[{from:'unknown',to:'wall',type:'FS',lag:0}]}),/relationships/);
const long={...f,rows:Array.from({length:53},(_,i)=>({...f.rows[i%5],id:'long-'+i,code:'L'+String(i).padStart(3,'0')})),links:[]};
assert.equal(G.pageCount(long),3);
const pages=Array.from({length:G.pageCount(long)},(_,i)=>G.svg(long,{print:true,offset:i*G.ROWS_PER_PAGE,limit:G.ROWS_PER_PAGE}));
assert.deepEqual(pages.map(svg=>[...svg.matchAll(/data-gantt-row/g)].length),[20,20,13]);
assert.equal(new Set(pages.flatMap(svg=>[...svg.matchAll(/data-gantt-row="([^"]+)"/g)].map(m=>m[1]))).size,53);
assert.equal(new Set(pages.map(svg=>svg.match(/2026-11-\d\d → 2026-11-\d\d/)?.[0])).size,1);
if(process.env.GANTT_QA_SVG)require('node:fs').writeFileSync(process.env.GANTT_QA_SVG,G.svg(f).replace('style="display:block;max-width:none"',''));
console.log('Gantt checks passed: recorded dates vs estimate, remaining-work gaps, baseline/no baseline, all rows across print pages, same axes, dependency arrows, milestone symbols and escaped labels.');
